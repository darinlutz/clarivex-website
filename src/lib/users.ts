import { randomBytes, scrypt, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';
import { isUniqueViolation, query, transaction } from './db';
import { ROLES } from './roles';
import { ACCOUNT_STATUS } from './accountStatus';

const scryptAsync = promisify(scrypt) as (password: string, salt: Buffer, keylen: number) => Promise<Buffer>;

const KEY_LENGTH = 64;

export type User = {
  id: number;
  userName: string;
  emailAddress: string;
  accountStatus: string;
  signupDate: string | null;
  subscriptionEndDate: string | null;
  // One of ROLES
  role: string;
  // False until a new account opens the link emailed at sign-up (src/lib/emailVerification.ts)
  emailVerified: boolean;
};

const USER_COLUMNS =
  'id, user_name, email_address, account_status, signup_date, subscription_end_date, role, email_verified';

// The site owner is made Admin on sign-up; everyone else is a User
const OWNER_EMAIL = 'darinlutz@yahoo.com';

export class EmailTakenError extends Error {
  constructor() {
    super('An account with that email address already exists');
  }
}

let schemaReady: Promise<void> | null = null;

// The clarivex schema holds the site's accounts and everything tied to one:
// Users, each user's own Friends, sign-in Sessions, PasswordResets and
// EmailVerifications links, plus SiteSettings (the Admin page's AI lockdown).
export function ensureUserSchema(): Promise<void> {
  if (!schemaReady) {
    schemaReady = transaction(async (client) => {
      // Concurrent CREATE ... IF NOT EXISTS can still collide in Postgres
      // when several server instances boot at once, so serialize them.
      await client.query("SELECT pg_advisory_xact_lock(hashtext('clarivex_user_schema'))");
      await client.query('CREATE SCHEMA IF NOT EXISTS clarivex');
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."Users" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_name TEXT NOT NULL,
        email_address TEXT NOT NULL,
        password TEXT NOT NULL,
        account_status TEXT NOT NULL DEFAULT '${ACCOUNT_STATUS.unsubscribed}',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        stripe_customer_id TEXT,
        stripe_subscription_id TEXT,
        signup_date TEXT,
        subscription_end_date TEXT,
        role TEXT NOT NULL DEFAULT '${ROLES.user}'
      )`);
      // New users are a User unless sign-up says otherwise (initialRole). Set
      // here too because the table was once created with a bad default.
      await client.query(`ALTER TABLE clarivex."Users" ALTER COLUMN role SET DEFAULT '${ROLES.user}'`);
      // Email addresses are unique regardless of case
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS users_email_address_key ON clarivex."Users" (lower(email_address))'
      );
      // Accounts from before email verification existed count as verified;
      // sign-up inserts new ones as unverified.
      await client.query(
        'ALTER TABLE clarivex."Users" ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT TRUE'
      );
      // The site owner is always an Admin
      await client.query(
        `UPDATE clarivex."Users" SET role = '${ROLES.admin}'
         WHERE lower(email_address) = $1 AND role <> '${ROLES.admin}'`,
        [OWNER_EMAIL]
      );
      // Each friend belongs to one user. `seq` records insertion order for listing.
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."Friends" (
        id TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES clarivex."Users"(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        country TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY
      )`);
      await client.query('CREATE INDEX IF NOT EXISTS friends_user_id_idx ON clarivex."Friends" (user_id, seq)');
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."Sessions" (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES clarivex."Users"(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`);
      await client.query('CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON clarivex."Sessions" (user_id)');
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."PasswordResets" (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES clarivex."Users"(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS password_resets_user_id_idx ON clarivex."PasswordResets" (user_id)'
      );
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."EmailVerifications" (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES clarivex."Users"(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS email_verifications_user_id_idx ON clarivex."EmailVerifications" (user_id)'
      );
      await client.query(`CREATE TABLE IF NOT EXISTS clarivex."SiteSettings" (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_by INTEGER REFERENCES clarivex."Users"(id) ON DELETE SET NULL
      )`);
    }).catch((error) => {
      schemaReady = null;
      throw error;
    });
  }
  return schemaReady;
}

// Stored as "scrypt$<salt hex>$<hash hex>" so the format is self-describing.
async function hashPassword(password: string): Promise<string> {
  const salt = randomBytes(16);
  const hash = await scryptAsync(password, salt, KEY_LENGTH);
  return `scrypt$${salt.toString('hex')}$${hash.toString('hex')}`;
}

async function verifyPassword(password: string, stored: string): Promise<boolean> {
  const [scheme, saltHex, hashHex] = stored.split('$');
  if (scheme !== 'scrypt' || !saltHex || !hashHex) return false;
  const expected = Buffer.from(hashHex, 'hex');
  const actual = await scryptAsync(password, Buffer.from(saltHex, 'hex'), expected.length);
  return timingSafeEqual(actual, expected);
}

function rowToUser(row: Record<string, unknown>): User {
  return {
    id: Number(row.id),
    userName: row.user_name as string,
    emailAddress: row.email_address as string,
    accountStatus: row.account_status as string,
    role: row.role as string,
    emailVerified: row.email_verified !== false,
    signupDate: (row.signup_date as string | null) ?? null,
    subscriptionEndDate: (row.subscription_end_date as string | null) ?? null,
  };
}

function initialRole(emailAddress: string): string {
  return emailAddress.trim().toLowerCase() === OWNER_EMAIL ? ROLES.admin : ROLES.user;
}

export async function createUser(input: {
  userName: string;
  emailAddress: string;
  password: string;
}): Promise<User> {
  // New accounts start unverified: they can't log in until they open the
  // link emailed to them.
  await ensureUserSchema();
  const passwordHash = await hashPassword(input.password);
  try {
    const rows = await query(
      `INSERT INTO clarivex."Users" (user_name, email_address, password, account_status, signup_date, role, email_verified)
       VALUES ($1, $2, $3, $6, $4, $5, FALSE)
       RETURNING ${USER_COLUMNS}`,
      [input.userName, input.emailAddress, passwordHash, new Date().toISOString(), initialRole(input.emailAddress), ACCOUNT_STATUS.unsubscribed]
    );
    return rowToUser(rows[0]);
  } catch (error) {
    if (isUniqueViolation(error)) {
      throw new EmailTakenError();
    }
    throw error;
  }
}

// Returns the user only when the email exists and the password matches.
export async function authenticateUser(emailAddress: string, password: string): Promise<User | null> {
  await ensureUserSchema();
  const [row] = await query(
    `SELECT ${USER_COLUMNS}, password FROM clarivex."Users" WHERE lower(email_address) = lower($1)`,
    [emailAddress]
  );
  if (!row) return null;
  const ok = await verifyPassword(password, row.password as string);
  return ok ? rowToUser(row) : null;
}

export async function getUserByEmail(emailAddress: string): Promise<User | null> {
  await ensureUserSchema();
  const [row] = await query(`SELECT ${USER_COLUMNS} FROM clarivex."Users" WHERE lower(email_address) = lower($1)`, [
    emailAddress,
  ]);
  return row ? rowToUser(row) : null;
}

// Also signs the user out everywhere, since an old session may belong to
// whoever knew the previous password.
export async function updatePassword(userId: number, password: string): Promise<void> {
  await ensureUserSchema();
  const passwordHash = await hashPassword(password);
  await transaction(async (client) => {
    await client.query('UPDATE clarivex."Users" SET password = $1 WHERE id = $2', [passwordHash, userId]);
    await client.query('DELETE FROM clarivex."Sessions" WHERE user_id = $1', [userId]);
  });
}

export async function getUserById(id: number): Promise<User | null> {
  await ensureUserSchema();
  const [row] = await query(`SELECT ${USER_COLUMNS} FROM clarivex."Users" WHERE id = $1`, [id]);
  return row ? rowToUser(row) : null;
}

export async function markEmailVerified(userId: number): Promise<void> {
  await ensureUserSchema();
  await query('UPDATE clarivex."Users" SET email_verified = TRUE WHERE id = $1', [userId]);
}
